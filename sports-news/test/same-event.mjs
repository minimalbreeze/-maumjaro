// 같은 대회를 두 번 쓴 짝만 고르는지 검사.
//
// 왜 이 검사가 중요한가 (2026-10-19)
//   운영자가 "겹치는 글 전부 처리해줘"라고 했다. 그런데 index-audit 의 묶음을
//   그대로 믿고 안내를 걸면 **독자를 엉뚱한 글로 보낸다.** 실제 묶음에
//   아시안투어 홍콩 오픈 ↔ 프랑스 오픈, 대학농구 ↔ 대학배구, ITTF ↔ WTT 가
//   들어 있었다. 안 하느니만 못한 일이다.
//
//   그래서 "차이가 전부 유형어일 때만 같은 대회"라는 좁은 규칙을 쓴다.
//   이 검사는 **그 좁음을 지킨다.** 느슨해지면 틀린 안내가 나간다.

import assert from 'node:assert/strict';
import { 같은대회인가, 차이낱말, 유형어, 짝고르기 } from '../src/wordpress/same-event.mjs';

let passed = 0;
const check = (name, fn) => {
  try { fn(); console.log(`  ✅ ${name}`); passed++; }
  catch (err) { console.log(`  ❌ ${name}\n     ${err.message}`); process.exitCode = 1; }
};

console.log('\n[같은 대회 짝 고르기]');

// 실제로 wiki 에서 나온 묶음들이다. 지어낸 예가 아니다.
const 다른대회 = [
  ['2025 ITTF(International Table Tennis Federation) 대회를 국내에서 시청하는 방법',
   '2025 WTT(World Table Tennis) 대회를 국내에서 시청하는 방법'],
  ['2025 KUSF 대학농구 U-리그 플레이오프 경기 일정,  대진표, 중계 시청 방법 총정리(왕좌를 향한 뜨거운 전쟁!)',
   '2025 KUSF 대학배구 U-리그 6강 플레이오프 중계 핫이슈! 진출팀·일정·우승예상 총정리'],
  ['2025 아시안투어 홍콩 오픈 경기 일정, 참가 선수, 시청 방법 총정리(장유빈, 자존심 회복 나선다!)',
   '2025 프랑스 오픈(롤랑가로스): 시청, 다시보기(조코비치의 마지막 도전?)'],
];

const 같은대회 = [
  ['2025 LPGA 한화 라이프플러스 인터내셔널 크라운 결과 중계 다시보기(호주, 첫 우승 쾌거!)',
   '2025 LPGA 한화 라이프플러스 인터내셔널 크라운 중계 경기일정 시간'],
  ['정읍 신태인파크골프장 이용료·예약 방법 (신용리 881)',
   '정읍 신태인파크골프장 이용료·예약 방법 (신용리 881)'],
];

check('다른 대회를 같은 대회로 묶지 않는다', () => {
  for (const [a, b] of 다른대회) {
    const r = 같은대회인가(a, b);
    assert.equal(r.같다, false, `같다고 했습니다: ${a.slice(0, 40)} ↔ ${b.slice(0, 40)}`);
    assert.ok(r.고유.length > 0, '왜 다른지 설명이 없습니다');
  }
});

check('같은 대회의 예고·결과 글은 짝으로 본다', () => {
  for (const [a, b] of 같은대회) {
    const r = 같은대회인가(a, b);
    assert.equal(r.같다, true, `다르다고 했습니다 (한쪽에만: ${r.고유.join(', ')})`);
  }
});

check('유형어에 고유명사를 넣지 않는다', () => {
  // 여기에 대회명·선수명·지명이 들어가면 규칙이 통째로 무너진다.
  const 들어가면안되는것 = ['ITTF', 'WTT', '대학농구', '대학배구', '프랑스', '홍콩',
    'LPGA', 'KPGA', '아시안투어', '전가람', '신태인'];
  for (const w of 들어가면안되는것) {
    assert.equal(유형어.has(w), false, `유형어에 '${w}' 가 들어 있습니다`);
  }
});

check('차이낱말은 양쪽을 다 본다', () => {
  // '결과'·'일정' 은 index-audit 의 흔한말 목록에서 **이미 걸러진다**.
  // 그래서 차이에 아예 안 나타난다 — 처음에 그걸 모르고 검사를 썼다가
  // 틀렸다. 흔한말에 없는 유형어로 본다.
  const 차이 = 차이낱말('가나다 다시보기', '가나다 생중계');
  assert.ok(차이.includes('다시보기'), `왼쪽에만 있는 말을 못 찾습니다: ${차이}`);
  assert.ok(차이.includes('생중계'), `오른쪽에만 있는 말을 못 찾습니다: ${차이}`);
});

check('흔한말이 걸러져도 고유명사는 차이에 남는다', () => {
  // 규칙이 서는 이유가 여기다. 흔한말(결과·일정·방법)은 빠지고 대회를
  // 가리키는 말만 남으므로, 차이에 무엇이 남는지가 곧 판정이 된다.
  const 차이 = 차이낱말('ITTF 대회 시청 방법', 'WTT 대회 시청 방법');
  assert.deepEqual(차이.sort(), ['ITTF', 'WTT'], `남은 것: ${차이}`);
});

check('짝은 옛글에서 새글로 간다', () => {
  const 글 = [
    { id: 100, date: '2025-05-20', title: '정읍 신태인파크골프장 이용료·예약 방법' },
    { id: 200, date: '2025-08-10', title: '정읍 신태인파크골프장 이용료·예약 방법' },
  ];
  const { 짝 } = 짝고르기(글);
  assert.equal(짝.length, 1, `짝이 ${짝.length}개입니다`);
  assert.equal(짝[0].옛글.id, 100, '옛글이 틀렸습니다');
  assert.equal(짝[0].새글.id, 200, '새글이 틀렸습니다');
});

check('날짜가 같으면 글 번호가 큰 쪽을 새글로 본다', () => {
  const 글 = [
    { id: 300, date: '2025-05-20', title: '가나다 대회 중계 일정' },
    { id: 400, date: '2025-05-20', title: '가나다 대회 중계 결과' },
  ];
  const { 짝 } = 짝고르기(글);
  assert.equal(짝.length, 1);
  assert.equal(짝[0].새글.id, 400);
});

check('다른 대회는 짝에서 빠지고 이유가 남는다', () => {
  const 글 = [
    { id: 1, date: '2025-06-19', title: '2025 ITTF 대회를 국내에서 시청하는 방법' },
    { id: 2, date: '2025-06-19', title: '2025 WTT 대회를 국내에서 시청하는 방법' },
  ];
  const { 짝, 버린것 } = 짝고르기(글);
  assert.equal(짝.length, 0, '틀린 짝을 만들었습니다');
  assert.equal(버린것.length, 1, '버린 이유를 안 남겼습니다');
  assert.ok(버린것[0].고유.length > 0);
});

console.log(`\n${process.exitCode ? '❌ 실패한 항목이 있습니다' : `✅ ${passed}개 항목 통과`}\n`);
