// "오래 가는 섹션"을 알아보는 낱말 — 한 군데서만 정한다.
//
// 왜 한 군데여야 하는가
//   2026-10-07 글 7793 에서 로그가 스스로 모순됐다.
//
//     ⚠️ 배경·원리·비교 섹션이 없습니다
//     ▶  오래 검색되는 섹션 보완 중
//     ✅ 보완 완료 — 본문 3668자          ← 고쳤다고 말하고
//     ❌ ⑤ 오래 가는 내용으로 확장했다     ← 안 고쳐졌다
//
//   두 검사가 같은 것을 다른 목록으로 재고 있었다.
//     lintArticle(write.mjs) : 배경·원리·비교·역사·규칙·계보
//     checkFlow ⑤ (flow.mjs) : 배경·원리·비교·역사·규칙·기록·데이터
//
//   보완 단계가 '## 📌 역대 우승자 계보' 같은 소제목을 만들면 앞쪽은 통과하고
//   뒤쪽은 실패한다. 그래서 "보완 완료"라고 찍어 놓고 ⑤ 는 ❌ 로 저장됐다.
//   돈을 들여 보완을 돌리고도 고쳐졌는지 아무도 확인하지 못한 것이다.
//
//   어제 분량 기준이 두 군데서 엇갈려 글이 떨어진 것과 같은 유형이다
//   (sports-news/CLAUDE.md "분량 기준은 한 군데서만 센다"). 같은 실수를
//   되풀이하지 않도록 이 파일 하나만 고치면 양쪽이 같이 움직이게 둔다.
//
// 어느 쪽에 맞출 것인가 — 엄격한 쪽이다.
//
//   처음에는 합집합(계보·기록·데이터 다 포함)으로 맞췄는데 기존 검사가 잡았다.
//   '## 📊 기록과 데이터'에 홈런·타점만 나열한 섹션이 ⑤ 를 통과해 버린다.
//   그건 뉴스지 오래 가는 내용이 아니다.
//
//   지시서가 정한 ⑤ 는 "규칙·원리·역사·비교"다(sports-news/CLAUDE.md 의 흐름 표,
//   flow.mjs 의 ⑤ 보완 문구). flow.mjs 가 '기록|데이터'까지 받아 준 것이 그
//   정의보다 느슨해진 쪽이었다. 느슨한 쪽에 맞추면 통계 나열 글이 ⑤ 를 통과한다.
//
//   계보는 넣는다. '역대 우승자 계보'는 내년에도 검색된다 — 7793 을 깨뜨린
//   낱말이 바로 이것이고, 빼야 할 이유가 없다.

/** 소제목이 "오래 가는 섹션"임을 알리는 낱말. */
export const LONGEVITY_WORDS = /배경|원리|비교|역사|규칙|계보/;

/** 소제목 하나가 오래 가는 섹션인가. */
export function 오래가는소제목인가(heading) {
  return LONGEVITY_WORDS.test(String(heading || ''));
}

/** 소제목 목록 중에 오래 가는 섹션이 있는가. */
export function 오래가는소제목찾기(headings = []) {
  return (Array.isArray(headings) ? headings : []).find(오래가는소제목인가) || null;
}

/** 보완 단계가 섹션을 새로 만들 때 쓰는 기본 소제목. 위 낱말을 반드시 담는다. */
export const LONGEVITY_HEADING = '## 📌 배경과 원리, 비슷한 사례 비교';
