// 같은 대회를 두 번 쓴 글 **짝**만 고른다. 읽기만 한다.
//
// 왜 따로 만드나
//   index-audit 의 `비슷한글묶기` 는 제목 낱말의 겹침 비율(0.35)로 묶는다.
//   각도를 손볼 후보를 사람이 훑어보기엔 그 정도가 맞지만, **자동으로 안내를
//   걸기에는 느슨하다.** 2026-10-19 에 실제로 이런 묶음이 나왔다.
//
//     3840 아시안투어 홍콩 오픈   ↔  424  프랑스 오픈(롤랑가로스)
//     3813 KUSF 대학농구          ↔  2089 KUSF 대학배구
//     779  ITTF 시청 방법         ↔  770  WTT 시청 방법
//
//   '시청·방법·대회·국내' 같은 흔한 말이 많으면 다른 대회끼리도 0.35 를 넘는다.
//   이대로 안내를 걸면 **독자를 엉뚱한 글로 보낸다.** 안 하느니만 못하다.
//
// 그래서 쓰는 규칙
//   두 제목의 낱말 차이가 **전부 유형어**일 때만 같은 대회로 본다.
//   유형어는 '결과·다시보기·경기일정·시간' 처럼 **같은 대회를 다른 각도에서
//   쓸 때 붙는 말**이다. 차이에 고유명사가 하나라도 있으면 다른 대회로 본다.
//
//   놓치는 짝이 생긴다. 예컨대 '전가람 우승, KPGA …' ↔ 'KPGA … (최경주,
//   이수민, 옥태훈 출전)' 은 같은 대회인데 선수 이름 때문에 걸러진다.
//   **그 쪽이 맞다** — 놓친 짝은 손해가 없지만 틀린 안내는 신뢰를 깎는다.
//   놓친 것은 사람이 목록을 보고 손으로 넣는다.

import { 발행글전부, 제목낱말, 비슷한글묶기 } from './index-audit.mjs';

/**
 * 같은 대회를 다른 각도에서 쓸 때 붙는 말.
 *
 * 대회의 신원을 가리키는 말(대회명·선수명·지명)은 여기 넣지 않는다.
 * 여기 든 말만으로 차이가 설명돼야 같은 대회로 본다.
 */
export const 유형어 = new Set([
  '중계', '생중계', '재방송', '다시보기', '하이라이트', '시청', '보는곳',
  '경기일정', '일정', '시간', '날짜', '편성', '채널',
  '결과', '성적', '우승', '준우승', '순위', '최종', '종합',
  '총정리', '정리', '완전정리', '안내', '가이드', '소개',
  '예고', '전망', '관전', '포인트', '핫이슈', '주요',
  '출전', '참가', '선수', '명단', '대진표', '대진',
  '상금', '방법', '국내', '어디서', '얼마', '언제',
]);

/** 두 글의 제목 낱말 차이 (양쪽 다 합친 대칭 차이). */
export function 차이낱말(a, b) {
  const A = new Set(제목낱말(a));
  const B = new Set(제목낱말(b));
  const 차이 = [];
  for (const w of A) if (!B.has(w)) 차이.push(w);
  for (const w of B) if (!A.has(w)) 차이.push(w);
  return 차이;
}

/**
 * 두 글이 같은 대회인가. 차이가 전부 유형어일 때만 참.
 * 설명을 함께 돌려준다 — 왜 아닌지 사람이 봐야 하기 때문이다.
 */
export function 같은대회인가(a, b) {
  const 차이 = 차이낱말(a, b);
  const 고유 = 차이.filter((w) => !유형어.has(w));
  return { 같다: 고유.length === 0, 차이, 고유 };
}

/**
 * 안내를 걸 짝 목록. 묶음 안에서 **가장 최신 글**을 가리킬 곳으로 삼고,
 * 나머지 중 '같은 대회'로 판정된 글만 보낸다.
 *
 * 날짜가 같으면 글 번호가 큰 쪽을 최신으로 본다.
 */
export function 짝고르기(글, { 기준 = 0.35 } = {}) {
  const 짝 = [];
  const 버린것 = [];
  for (const 무리 of 비슷한글묶기(글, 기준)) {
    const 정렬 = [...무리].sort((x, y) => (x.date === y.date ? y.id - x.id : (x.date < y.date ? 1 : -1)));
    const 최신 = 정렬[0];
    for (const p of 정렬.slice(1)) {
      const r = 같은대회인가(최신.title, p.title);
      if (r.같다) 짝.push({ 옛글: p, 새글: 최신 });
      else 버린것.push({ 옛글: p, 새글: 최신, 고유: r.고유 });
    }
  }
  return { 짝, 버린것 };
}

async function main() {
  const 전부보기 = process.argv.includes('--버린것도');
  const 글 = await 발행글전부();
  console.log(`\n발행된 글 ${글.length}편`);

  const { 짝, 버린것 } = 짝고르기(글);

  console.log(`\n[같은 대회로 판정 — 안내를 걸 짝] ${짝.length}쌍`);
  for (const { 옛글, 새글 } of 짝) {
    console.log('');
    console.log(`   옛글 ${옛글.id}  ${옛글.date}  ${옛글.title}`);
    console.log(`   새글 ${새글.id}  ${새글.date}  ${새글.title}`);
  }
  if (!짝.length) console.log('   없습니다.');

  console.log(`\n[다른 대회로 보고 건너뛴 것] ${버린것.length}쌍`);
  if (전부보기) {
    // **한 쌍에 한 줄.** 222쌍을 사람이 훑어야 하므로 짧아야 한다.
    // 공통 낱말이 같은 대회인지를 가르는 핵심이라 그것부터 보여준다.
    console.log('   형식: 옛글→새글 | 공통 | 옛글만 | 새글만\n');
    for (const { 옛글, 새글 } of 버린것) {
      const A = new Set(제목낱말(옛글.title));
      const B = new Set(제목낱말(새글.title));
      const 공통 = [...A].filter((w) => B.has(w));
      const 옛만 = [...A].filter((w) => !B.has(w));
      const 새만 = [...B].filter((w) => !A.has(w));
      console.log(`   ${옛글.id}→${새글.id} | ${공통.join(' ')} | ${옛만.join(' ')} | ${새만.join(' ')}`);
    }
  } else {
    console.log('   (--버린것도 를 붙이면 무엇을 왜 건너뛰었는지 봅니다)');
  }
  console.log('\n   읽기만 했습니다. 안내는 add-notice.mjs 가 넣습니다.\n');
}

if (import.meta.url === `file://${process.argv[1]}`) await main();
