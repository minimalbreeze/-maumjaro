/** 표의 한 항목을 글에 적용한다. 가드에 걸리는 자리는 건너뛴다. */
export function 한항목고치기(text, 항목) {
  const 원본 = String(text || '');
  if (!원본.includes(항목.틀린)) return { after: 원본, 횟수: 0 };

  let 결과 = '';
  let i = 0;
  let 횟수 = 0;
  while (i < 원본.length) {
    const at = 원본.indexOf(항목.틀린, i);
    if (at < 0) { 결과 += 원본.slice(i); break; }
    결과 += 원본.slice(i, at);
    // 가드는 "틀린 말이 시작되는 자리부터"의 앞뒤 몇 글자를 보고 판단한다.
    const 둘레 = 원본.slice(Math.max(0, at - 2), at + 항목.틀린.length + 2);
    if (항목.가드 && 항목.가드.test(둘레)) {
      결과 += 항목.틀린;            // 멀쩡한 낱말이다. 그대로 둔다
    } else {
      결과 += 항목.맞는;
      횟수 += 1;
    }
    i = at + 항목.틀린.length;
  }
  return { after: 결과, 횟수 };
}

/**
 * 그 항목을 이 글에 적용해도 되나. `글` 이 적힌 항목은 거기 적힌 글에서만.
 *
 * postId 를 안 넘기면(옛 호출부·검사) 글 범위가 없는 항목만 적용한다 —
 * 모르는 글에 사실 수정을 흘리지 않는다.
 */
export function 이글에쓰나(항목, postId) {
  if (!항목.글) return true;
  return postId != null && 항목.글.includes(Number(postId));
}

/** 표 전체를 글에 적용한다. postId 를 주면 그 글에 매인 항목도 함께 본다. */
/**
 * **덧붙이는 항목인가.** `맞는` 안에 `틀린`이 통째로 들어 있는 항목이다.
 *
 * 2026-10-19: 이런 항목은 **고친 뒤에도 틀린 문자열이 그대로 남는다.**
 * 그래서 다시 돌리면 또 걸리고, 돌릴 때마다 내용이 한 번씩 더 붙는다.
 *
 *   "별도 문의 필요"  →  "별도 문의 필요 (전화 032-899-4891)"
 *   다시 돌리면       →  "별도 문의 필요 (전화 032-899-4891) (전화 032-899-4891)"
 *
 * 실제로 8592 에서 8강 섹션 전체가 두 번 붙을 뻔했고, 전화번호를 넣은
 * 세 항목도 같은 꼴이었다. 범위를 좁혀 돌린 덕에 터지지 않았다.
 */
export function 덧붙이는항목인가(항목) {
  const 틀린 = String(항목?.틀린 ?? '');
  const 맞는 = String(항목?.맞는 ?? '');
  return Boolean(틀린) && 맞는.includes(틀린);
}

/** 덧붙이는 항목인데 이미 들어가 있으면 또 넣지 않는다. */
export function 이미넣었나(text, 항목) {
  if (!덧붙이는항목인가(항목)) return false;
  return String(text || '').includes(String(항목?.맞는 ?? ''));
}

export function 고치기(text, 표 = 바로잡기, postId = null) {
  let 결과 = String(text || '');
  const 바뀐것 = [];
  for (const 항목 of 표) {
    if (!이글에쓰나(항목, postId)) continue;
    // 덧붙이는 항목은 한 번만 넣는다. 안 막으면 돌릴 때마다 쌓인다.
    if (이미넣었나(결과, 항목)) continue;
    const r = 한항목고치기(결과, 항목);
    결과 = r.after;
    if (r.횟수) 바뀐것.push({ 틀린: 항목.틀린, 맞는: 항목.맞는, 횟수: r.횟수 });
  }
  return { after: 결과, 바뀐것 };
}

/**
 * 표에 적힌 것 말고는 아무것도 안 바뀌었나. 보내기 전 마지막 확인.
 *
 * 원래 글에 표를 한 번 더 적용해서 보낼 글과 **글자 하나까지 같은지** 본다.
 * 다르면 그 글은 건너뛴다 — 내가 모르는 변화가 섞였다는 뜻이다.
 */
export function 오타만바뀌었나(before, after, 표 = 바로잡기, postId = null) {
  return 고치기(before, 표, postId).after === after;
}

// ── 오타 후보 찾기 (고치지 않는다) ─────────────────────────
//
// 생각 — 오타는 **딱 한 번만 나오고, 자주 나오는 말과 한 글자만 다르다.**
// "아구"는 633편에 한 번, "야구"는 수십 번 나온다. 한 글자 차이다.
// 맞춤법 지식이 없어도 이 모양만으로 후보를 꽤 건진다.
//
// 이건 후보일 뿐이고 **틀릴 수 있다.** 그래서 고치지 않고 보여만 준다.

/** 한 글자 고쳐서 같아지는 거리(최대 2까지만 센다. 그 이상은 다른 말이다). */
export function 글자거리(a, b) {
  const A = String(a); const B = String(b);
  if (Math.abs(A.length - B.length) > 1) return 9;
  const 표 = Array.from({ length: A.length + 1 }, (_, i) => [i, ...Array(B.length).fill(0)]);
  for (let j = 0; j <= B.length; j += 1) 표[0][j] = j;
  for (let i = 1; i <= A.length; i += 1) {
    for (let j = 1; j <= B.length; j += 1) {
      표[i][j] = A[i - 1] === B[j - 1]
        ? 표[i - 1][j - 1]
        : 1 + Math.min(표[i - 1][j - 1], 표[i - 1][j], 표[i][j - 1]);
    }
  }
  return 표[A.length][B.length];
}

/** 제목들을 낱말로 쪼갠다. 숫자·영문은 오타 판단 대상이 아니다. */
export function 한글낱말(text) {
  return String(text || '').match(/[가-힣]{2,}/g) || [];
}

/**
 * 한쪽이 다른 쪽에 붙은 꼴인가. 조사·합성어다. 오타가 아니다.
 *
 * 실측 (2026-10-10, 633편): 후보 275개 중 54개가 이 꼴이었다 —
 * 포인트는/포인트, 경기를/경기, 상금왕/상금, 신세계/세계, 지원금/지원,
 * 박현경의/박현경. 전부 멀쩡한 말이다.
 */
export function 붙은꼴인가(a, b) {
  const A = String(a); const B = String(b);
  if (A === B) return false;
  return A.startsWith(B) || A.endsWith(B) || B.startsWith(A) || B.endsWith(A);
}

/**
 * 오타 후보를 찾는다.
 *
 * **거짓 양성이 많다. 실측 적중률은 1%쯤이다** — 633편에서 후보 275개가
 * 나왔고 실제 오타는 3개였다(다십보기·혹태훈·랭팅). 두 글자 한국어 낱말은
 * 한 글자만 달라도 둘 다 멀쩡한 말인 경우가 흔하다(시간/구간, 결과/효과,
 * 일정/가정). 그래서 이 함수는 **읽을 목록을 만드는 체**이고, 판단은
 * 사람이 한다. 자동으로 고치는 데 쓰지 않는다.
 *
 * 긴 낱말(3글자 이상)은 우연히 겹칠 확률이 낮아 적중률이 훨씬 높다.
 * 그래서 `주목` 을 달아 먼저 보게 한다 — 실측으로 275개 → 15개로 줄고
 * 그 안에 진짜 2개가 들어 있었다.
 *
 * @param 글       제목을 가진 글 목록
 * @param 드문것   이 횟수까지를 "드물다"고 본다 (기본 1 = 딱 한 번)
 * @param 흔한것   이 횟수부터를 "흔하다"고 본다 (기본 5)
 */
export function 오타후보(글 = [], { 드문것 = 1, 흔한것 = 5 } = {}) {
  const 셈 = new Map();
  const 어디 = new Map();
  for (const p of 글) {
    for (const w of 한글낱말(p.title)) {
      셈.set(w, (셈.get(w) || 0) + 1);
      if (!어디.has(w)) 어디.set(w, []);
      if (어디.get(w).length < 3) 어디.get(w).push(p);
    }
  }
  const 흔한 = [...셈.entries()].filter(([, n]) => n >= 흔한것).map(([w]) => w);
  const 후보 = [];
  for (const [w, n] of 셈) {
    if (n > 드문것) continue;
    for (const 기준 of 흔한) {
      if (w === 기준) continue;
      if (글자거리(w, 기준) !== 1) continue;
      if (붙은꼴인가(w, 기준)) continue;   // 조사·합성어다
      후보.push({
        낱말: w, 횟수: n, 닮은말: 기준, 닮은말횟수: 셈.get(기준),
        글: 어디.get(w) || [],
        // 3글자 이상은 우연히 겹칠 확률이 낮다. 먼저 보게 한다.
        주목: w.length >= 3,
      });
      break;
    }
  }
  return 후보.sort((a, b) => b.닮은말횟수 - a.닮은말횟수);
}

