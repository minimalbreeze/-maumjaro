// 보강 1순위 글에 **무엇이 실제로 모자란지** 센다. 읽기만 한다(0원).
//
//   node src/wordpress/reinforce-scan.mjs
//
// 왜 필요한가 (2026-10-19)
//   보강 1순위는 "시설·상금 글 중 3,000자 미만" 62편이다. 그런데 글자수만
//   보고 돈을 쓰면 안 된다. sports-news/CLAUDE.md ②절이 구글 문서를 인용해
//   못 박아 둔 것이 있다.
//
//     "콘텐츠 길이 자체는 순위 결정과 관련 없습니다"
//     "못 채웠으면 길이를 늘릴 생각 대신 ⑤ 배경·원리·비교에 쓸 수 있는
//      것이 남았는지만 본다. 없으면 그대로 둔다."
//
//   그리고 실제로 1693(제일CC)을 열어 보니 **분량이 아니라 오류**였다 —
//   리베라CC 요금이 먼저 나왔다. 1650 은 이미지 alt 가 남의 골프장
//   이름이었다. 둘 다 글을 늘려서 해결되는 문제가 아니다.
//
//   62편 × 190~370원 = 1만 2천~2만 3천원이다. 그 돈을 쓸 글과 0원으로
//   고칠 글과 그대로 둘 글을 먼저 가른다.
//
// 어떻게 가르나 — 독자가 시설 글에서 찾는 것으로 센다.
//   config/search-demand.md 실측: "시설명 + 이용방법/예약/복장/가격/가는 길"
//   이 CTR 10~25% 다. 그 다섯 가지가 글에 있는지를 본다. 요금·전화번호·
//   주소·운영시간이 다 있으면 **짧아도 독자가 찾는 것은 다 있는 글**이다.
//
//   ① 0원 고칠것  — alt 가 둘이거나 다른 시설 이름이 섞였다(이미 도구가 있다)
//   ② 돈 드는것   — 요금·연락처 같은 **사실 자체가 없다**. 조사가 필요하다
//   ③ 그대로 둘것 — 사실은 다 있고 길이만 짧다. CLAUDE.md 가 두라고 한 쪽이다
//
// 이 도구는 **세기만 한다.** 무엇에 돈을 쓸지는 사람이 정한다.

import { wpFetch } from './client.mjs';
import { 발행글전부, 보강1순위, 글유형 } from './index-audit.mjs';
import { 섞인것, 시설이름, 지명뿐인가 } from './facility-mix.mjs';
import { alt값들 } from './dup-alt.mjs';

/** 태그를 걷어내고 사람이 읽는 글자만 남긴다. */
export const 글자만 = (html) => String(html || '')
  .replace(/<[^>]+>/g, ' ').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();

/**
 * 독자가 시설 글에서 찾는 것들. config/search-demand.md 실측 순서다.
 *
 * 숫자가 든 것만 센다 — "이용료는 저렴합니다" 는 요금을 적은 것이 아니다.
 * 글에 들어 있는지를 보는 것이고, 값이 맞는지는 사람이 본다.
 */
/**
 * 돈이 적혔는지 보는 눈금.
 *
 * 2026-10-19: 처음에 `[0-9][0-9,]*\s*(원|달러|만원|억)` 로 썼다가
 * **`960만 달러`·`723만 달러` 를 놓쳤다.** 숫자 바로 뒤에 단위가 와야 하는데
 * 한국어 수사(만·천·억)가 끼어 있기 때문이다. LPGA·ATP 상금은 거의 다 이
 * 꼴이라, 상금이 이미 적힌 글을 "상금액 없음" 으로 보고 돈을 쓸 뻔했다.
 *
 * 홀 수·연도·전화번호를 돈으로 세지 않는 것도 함께 지킨다 — 검사에 있다.
 */
export const 돈눈금 = /[0-9][0-9,.]*\s*(?:억|조)?\s*(?:[0-9][0-9,.]*)?\s*(?:천|백)?\s*만?\s*(?:원|달러|엔|유로|위안|파운드)|[0-9][0-9,.]*\s*(?:억|조)/;

export const 찾는것 = [
  { 이름: '요금', 본다: (t) => 돈눈금.test(t) },
  { 이름: '전화', 본다: (t) => /0\d{1,2}[-\s]?\d{3,4}[-\s]?\d{4}/.test(t) },
  { 이름: '주소', 본다: (t) => /(로|길|동|리|면|읍)\s?\d/.test(t) },
  { 이름: '운영시간', 본다: (t) => /(\d{1,2}\s*시|오전|오후|일몰|연중무휴|휴무)/.test(t) },
  { 이름: '예약방법', 본다: (t) => /(예약|선착순|현장\s?접수|키오스크|전화\s?문의)/.test(t) },
];

/** 상금 글은 찾는 것이 다르다. 액수와 연도가 핵이다. */
export const 상금이찾는것 = [
  { 이름: '상금액', 본다: (t) => 돈눈금.test(t) },
  { 이름: '연도', 본다: (t) => /20\d{2}\s*년?/.test(t) },
  { 이름: '순위별', 본다: (t) => /(우승|준우승|\d\s*위|공동)/.test(t) },
];

/** 글 하나를 센다. 저장하지 않는다. */
export function 재어보기(글, { 다른이름 = [] } = {}) {
  const 본문 = 글자만(글?.content);
  const 유형 = 글유형(글?.title);
  const 항목 = 유형 === '상금' ? 상금이찾는것 : 찾는것;

  const 있는것 = [];
  const 없는것 = [];
  for (const x of 항목) (x.본다(본문) ? 있는것 : 없는것).push(x.이름);

  // 0원으로 고칠 수 있는 것들. 이미 도구가 있다.
  const 이미지 = [...String(글?.content || '').matchAll(/<img\b[^>]*>/gi)];
  const alt둘 = 이미지.filter((m) => alt값들(m[0]).length >= 2).length;
  const 섞임 = 유형 === '시설' ? 섞인것(글, 다른이름) : { 섞인이름: [], 잘렸나: false };

  const 고칠것 = [];
  if (alt둘) 고칠것.push(`alt 가 둘인 이미지 ${alt둘}장`);
  if (섞임.섞인이름.length) 고칠것.push(`다른 시설 이름 ${섞임.섞인이름.map((x) => `${x.이름}×${x.횟수}`).join(', ')}`);
  if (섞임.잘렸나) 고칠것.push('문장이 잘린 자리');

  // 셋 중 어디로 가는가. 0원 고칠 것이 있으면 그것이 먼저다.
  const 갈곳 = 고칠것.length ? '0원' : (없는것.length ? '돈' : '그대로');

  return {
    id: 글?.id, title: 글?.title, 글자수: 글?.글자수, 유형,
    있는것, 없는것, 고칠것, 갈곳, 이미지수: 이미지.length,
  };
}

async function main() {
  console.log('\n────────────────────────────────────────────────────────');
  console.log('📋 보강 1순위 글에 무엇이 모자란지 센다 (읽기만 함 · 0원)');
  console.log('────────────────────────────────────────────────────────');

  const 글 = await 발행글전부();
  const 대상 = 보강1순위(글);
  console.log(`\n발행된 글 ${글.length}편 · 보강 1순위 ${대상.length}편`);

  // 다른 시설 이름 — 섞인 것을 보는 데 쓴다. 지명 한 덩어리는 뺀다.
  const 다른이름 = [...new Map(
    글.filter((p) => 글유형(p.title) === '시설')
      .map((p) => ({ 이름: 시설이름(p.title), 주소: '' }))
      .filter((x) => x.이름 && !지명뿐인가(x.이름))
      .map((x) => [x.이름, x]),
  ).values()];

  const 결과 = [];
  for (const p of 대상) {
    const { data } = await wpFetch(`/wp/v2/posts/${p.id}`, { query: { context: 'edit' } });
    const content = data?.content?.raw ?? data?.content?.rendered ?? '';
    결과.push(재어보기({ ...p, content }, { 다른이름 }));
  }

  // **그대로 → 돈 → 0원** 순서로 찍는다. 로그 요약은 tail -60 만 보여주므로
  // 할 일이 뒤에 와야 살아남는다. 2026-10-19 에 거꾸로 찍어서 안 할 일(그대로
  // 30편)만 남고 0원 29편·돈 6편 목록이 밀려 나갔다 — #212 와 같은 사고다.
  const 묶음 = ['그대로', '돈', '0원'];
  const 설명 = {
    '0원': '0원으로 고칠 것 — 이미 도구가 있다(alt 둘 · 섞인 이름 · 잘린 문장)',
    '돈': '사실이 모자란 것 — 조사가 필요하다 (글당 190~370원)',
    '그대로': '독자가 찾는 것은 다 있고 길이만 짧다 — CLAUDE.md 가 두라고 한 쪽',
  };

  for (const 키 of 묶음) {
    const 목록 = 결과.filter((r) => r.갈곳 === 키);
    console.log(`\n\n[${키}] ${목록.length}편 — ${설명[키]}\n`);
    for (const r of 목록) {
      console.log(`   ${r.id}  ${String(r.글자수).padStart(5)}자  ${r.유형}  ${String(r.title).slice(0, 42)}`);
      if (r.고칠것.length) console.log(`        🔧 ${r.고칠것.join(' · ')}`);
      if (r.없는것.length) console.log(`        ❌ 없는 것: ${r.없는것.join(', ')}`);
      if (키 === '그대로') console.log(`        ✅ 있는 것: ${r.있는것.join(', ')}`);
    }
  }

  const 센다 = (k) => 결과.filter((r) => r.갈곳 === k).length;
  const 돈 = 센다('돈');
  console.log('\n\n이 도구는 세기만 합니다. 무엇에 돈을 쓸지는 사람이 정합니다.');
  const 번호 = (k) => 결과.filter((r) => r.갈곳 === k).map((r) => r.id).join(' ');
  console.log(`\n▶ 보강 1순위 ${결과.length}편 = 0원 ${센다('0원')}편 · 돈 ${돈}편 · 그대로 ${센다('그대로')}편`);
  console.log(`   돈 드는 ${돈}편을 다 돌리면 ${(돈 * 190).toLocaleString()}~${(돈 * 370).toLocaleString()}원입니다`);
  console.log(`   0원: ${번호('0원')}`);
  console.log(`   돈 : ${번호('돈')}\n`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  (await import('../utils/env.mjs')).loadEnv();
  await main();
}
