/**
 * 나레이션에서 광고가 막힐 표현을 찾는다.
 *
 * 반환: [{ word, line }] — 없으면 빈 배열
 */
export function findAdUnsafe(text) {
  const found = [];
  const lines = String(text || '').split('\n');
  for (const line of lines) {
    for (const word of AD_UNSAFE_NARRATION) {
      if (line.includes(word)) found.push({ word, line: line.trim().slice(0, 60) });
    }
  }
  return found;
}

/** 제목이 오해를 부르는지 본다. 반환: [{ pattern, why }] */
export function checkTitle(title) {
  const t = String(title || '');
  const problems = [];
  for (const { re, why } of MISLEADING_TITLE_PATTERNS) {
    if (re.test(t)) problems.push({ pattern: re.source, why });
  }
  // 길이도 본다. 너무 길면 뒷부분이 잘려 "약속만 보이고 단서는 안 보이는"
  // 제목이 된다.
  if (t.length > 60) {
    problems.push({ pattern: 'length', why: `제목이 ${t.length}자입니다. 60자가 넘으면 모바일에서 잘립니다` });
  }
  return problems;
}

