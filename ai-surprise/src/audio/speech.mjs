// 읽을 글을 따로 만든다.
//
// 자막에 보이는 글과 **읽는 글이 같아야 할 이유가 없다.** 자막은 눈으로
// 읽고, 음성은 귀로 듣는다. 따옴표는 눈에는 "여기까지가 남의 말"이라고
// 알려 주지만, 귀에는 아무것도 아니다 — 그런데 음성 모델은 거기서
// 쉬어 버린다.
//
// 3화를 듣고 운영자가 잡은 것 두 가지다(2026-10-31).
//
//   1. 따옴표 뒤가 느리고 어색하다
//   2. 선수 이름(유로결)이 어색하게 읽힌다
//
// Chirp3-HD 목소리는 **SSML을 받지 않는다.** 그래서 쉼이나 발음을
// 태그로 지정할 길이 없고, 글자만으로 해결해야 한다. 이 파일이 그
// 일을 한다.

/**
 * 읽을 때 뗄 따옴표.
 *
 * 안쪽 글자는 그대로 두고 **기호만** 뗀다. 겹따옴표·홑따옴표·곁낫표를
 * 모두 본다. 자막에는 그대로 남으므로 "남의 말"이라는 표시는 눈으로
 * 전달된다.
 *
 * ⚠️ 홑따옴표는 조심해야 한다. "구단의 '지금'" 처럼 강조로 쓴 것도 있고,
 *    영어 축약(don't)에도 들어간다. 그래서 **한글·한자 사이에 든 것만**
 *    뗀다. don't 의 따옴표는 건드리지 않는다.
 */
const QUOTE_PAIRS = [
  // 겹따옴표는 양쪽을 다 뗀다. 영어 축약에 쓰이지 않아 안전하다.
  // ⚠️ 글자를 그대로 적으면 편집기나 도구가 둥근 따옴표를 직선으로
  //    바꿔 놓는다(실제로 한 번 그렇게 되어 검사가 깨졌다).
  //    그래서 **유니코드 번호로만** 적는다.
  [/["“”„〝〞＂]/g, ''],
  [/[「」『』]/g, ''],
];

/**
 * 읽기 발음을 바로잡는 낱말.
 *
 * 왼쪽이 대본에 쓰는 글자, 오른쪽이 **읽힐 글자**다. 자막에는 왼쪽이
 * 그대로 나간다.
 *
 * ⚠️ 여기 넣는 것은 **실제로 들어 보고 이상했던 것만**이다. 짐작으로
 *    넣으면 멀쩡한 발음을 망친다. 넣을 때는 `node src/main.mjs say`
 *    로 양쪽을 다 만들어 듣고 고른다.
 *
 * 비어 있는 것이 정상이다 — 들어 보기 전에는 아무것도 넣지 않는다.
 */
export const PRONOUNCE = new Map([]);

/**
 * 셋 이상을 쉼표로 늘어놓은 자리.
 *
 * "노시환, 유로결, 변우혁." 처럼 쉼표로 이은 이름 목록에서 음성 모델이
 * 쉼표마다 길게 쉰다. 눈으로 읽으면 자연스러운 줄이 귀로는 뚝뚝
 * 끊긴다.
 *
 * 쉼표를 **가운뎃점으로 바꾸면** 쉼이 짧아진다. 뜻은 같고 기호만
 * 다르다. 자막에는 쉼표가 그대로 남는다.
 *
 * ⚠️ 이것도 들어 보고 켠다. 기본은 꺼 둔다 — 쉼표를 바꿨는데 더
 *    어색해지면 되돌릴 수 없는 종류의 손해(다시 만드는 돈)가 난다.
 */
export const SOFTEN_LIST_COMMAS = false;

/** 2음절 이상 한글 낱말 사이에 든 홑따옴표만 떼는 자리. */
const INNER_SINGLE_QUOTE = /(?<=[가-힣0-9])[\u0027\u2018\u2019](?=[가-힣0-9])/g;

/** 한글 낱말을 감싼 홑따옴표. */
const WRAPPING_SINGLE_QUOTE = /[\u0027\u2018\u2019](?=[가-힣])|(?<=[가-힣])[\u0027\u2018\u2019](?=[\s,.?!)\]]|$)/g;

/**
 * 한 문단을 **읽을 글**로 바꾼다.
 *
 * 하는 일
 *  1) 따옴표를 뗀다 (안쪽 글자는 그대로)
 *  2) 발음 사전을 적용한다
 *  3) 쉼표가 늘어선 자리를 누그러뜨린다 (SOFTEN_LIST_COMMAS 가 켜졌을 때만)
 *  4) 겹친 공백을 하나로 모은다
 *
 * 글자를 **지우지 않는다.** 기호만 바꾼다. 읽을 말이 자막에 보이는
 * 말과 달라지면 보는 사람이 바로 알아챈다.
 */
export function speechText(text) {
  let out = String(text ?? '');

  for (const [re, to] of QUOTE_PAIRS) out = out.replace(re, to);
  out = out.replace(WRAPPING_SINGLE_QUOTE, '');
  out = out.replace(INNER_SINGLE_QUOTE, '');

  for (const [from, to] of PRONOUNCE) out = out.split(from).join(to);

  if (SOFTEN_LIST_COMMAS) out = softenListCommas(out);

  return out.replace(/[ \t]{2,}/g, ' ').trim();
}

/**
 * 셋 이상 늘어선 쉼표를 가운뎃점으로 바꾼다.
 *
 * "가, 나, 다" → "가·나·다". 둘뿐인 "가, 나" 는 건드리지 않는다 —
 * 그 정도 쉼은 자연스럽다.
 */
export function softenListCommas(text) {
  // 한글 낱말 + 쉼표가 두 번 이상 이어지는 자리를 찾는다.
  return String(text ?? '').replace(
    /([가-힣]{2,})(, )([가-힣]{2,})(, )([가-힣]{2,})/g,
    (_m, a, _c1, b, _c2, c) => `${a}·${b}·${c}`
  );
}

/**
 * 읽을 글이 보이는 글과 **뜻이 같은지** 확인한다.
 *
 * 기호만 떼기로 했으므로, 한글·숫자·영문만 남겨서 비교하면 똑같아야
 * 한다. 다르면 글자를 건드린 것이고 그건 버그다.
 *
 * 발음 사전으로 바꾼 낱말은 당연히 다르므로 그 낱말은 빼고 본다.
 */
export function sameMeaning(original, speech) {
  const strip = (s) => {
    let t = String(s ?? '');
    for (const [from, to] of PRONOUNCE) {
      t = t.split(from).join('§').split(to).join('§');
    }
    if (SOFTEN_LIST_COMMAS) t = t.replace(/·/g, '');
    return t.replace(/[^가-힣0-9A-Za-z§]/g, '');
  };
  return strip(original) === strip(speech);
}
