/** 2음절 이상 한글 낱말 사이에 든 홑따옴표만 떼는 자리. */
const INNER_SINGLE_QUOTE = /(?<=[가-힣0-9])[\u0027\u2018\u2019](?=[가-힣0-9])/g;

/** 한글 낱말을 감싼 홑따옴표. */
const WRAPPING_SINGLE_QUOTE = /[\u0027\u2018\u2019](?=[가-힣])|(?<=[가-힣])[\u0027\u2018\u2019](?=[\s,.?!)\]]|$)/g;

/**
 * 한 문단을 **읽을 글**로 바꾼다.
 *
 * 하는 일
 *  1) 따옴표를 뗀다 (안쪽 글자는 그대로)
 *  2) 발음 사전을 적용한다
 *  3) 쉼표가 늘어선 자리를 누그러뜨린다 (SOFTEN_LIST_COMMAS 가 켜졌을 때만)
 *  4) 겹친 공백을 하나로 모은다
 *
 * 글자를 **지우지 않는다.** 기호만 바꾼다. 읽을 말이 자막에 보이는
 * 말과 달라지면 보는 사람이 바로 알아챈다.
 */
export function speechText(text) {
  let out = String(text ?? '');

  for (const [re, to] of QUOTE_PAIRS) out = out.replace(re, to);
  out = out.replace(WRAPPING_SINGLE_QUOTE, '');
  out = out.replace(INNER_SINGLE_QUOTE, '');

  // ── 숫자를 읽는 글로 (2026-11-07 운영자) ──
  //
  //   "5.26은 숫자로 적어야지. 읽을 때는 한글로 읽지만."
  //   "42억 이런 것도 숫자로 자막을 만들어야지."
  //   "79승 2무 63패 이런 것도 자막이 숫자로 되어야지."
  //
  // 그래서 대본에는 숫자를 **숫자로** 쓴다. 자막에 그대로 나가고,
  // 읽을 글만 여기서 한글이 된다. KIA 와 같은 꼴이다.
  //
  // ⚠️ 차례가 중요하다. 숫자를 먼저 풀어야 joinNumberUnits 가
  //    "2회 말" → "이 회 말" → "이회말" 까지 갈 수 있다.
  out = readNumbers(out);

  out = joinNumberUnits(out);

  for (const [from, to] of FA_GRADE) out = out.split(from).join(to);
  for (const [from, to] of PRONOUNCE) out = out.split(from).join(to);
  for (const [from, to] of READ_AS_ONE) out = out.split(from).join(to);
  for (const [from, to] of READ_BREAK) out = out.split(from).join(to);

  if (SOFTEN_LIST_COMMAS) out = softenListCommas(out);

  return out.replace(/[ \t]{2,}/g, ' ').trim();
}

/**
 * 한글 숫자와 단위 사이의 공백을 없앤다.
 *
 *   "이 회 말"   → "이회말"
 *   "삼 차전"    → "삼차전"
 *   "일 번"      → "일번"
 *   "삼 루"      → "삼루"
 *
 * 글자는 그대로다. 공백만 지운다 — sameMeaning() 이 공백을 빼고
 * 비교하므로 자막과 뜻이 같은지 검사도 그대로 통과한다.
 */
export function joinNumberUnits(text) {
  let out = String(text ?? '');
  const num = '[일이삼사오육칠팔구십백천만]+';
  for (const unit of JOIN_UNITS) {
    // ⚠️ 처음에 뒤에 한글이 오면 건드리지 말라고 막아 뒀는데, 그러면
    //    **아무것도 안 붙는다.** 한국어는 단위 뒤에 조사가 늘 따라온다 —
    //    "이 회 말에", "삼 차전에서", "일 번은", "삼 루까지".
    //    조사를 막으면 실제 문장에서 한 번도 안 걸린다.
    out = out.replace(new RegExp(`(${num}) (${unit})`, 'g'), '$1$2');
  }
  // "이회 말" 처럼 반만 붙은 것도 마저 붙인다.
  for (const half of INNING_HALF) {
    out = out.replace(new RegExp(`(${num}회) (${half})`, 'g'), '$1$2');
  }
  return out;
}

/**
 * 셋 이상 늘어선 쉼표를 가운뎃점으로 바꾼다.
 *
 * "가, 나, 다" → "가·나·다". 둘뿐인 "가, 나" 는 건드리지 않는다 —
 * 그 정도 쉼은 자연스럽다.
 */
export function softenListCommas(text) {
  // 한글 낱말 + 쉼표가 두 번 이상 이어지는 자리를 찾는다.
  return String(text ?? '').replace(
    /([가-힣]{2,})(, )([가-힣]{2,})(, )([가-힣]{2,})/g,
    (_m, a, _c1, b, _c2, c) => `${a}·${b}·${c}`
  );
}

/**
 * 읽을 글이 보이는 글과 **뜻이 같은지** 확인한다.
 *
 * 기호만 떼기로 했으므로, 한글·숫자·영문만 남겨서 비교하면 똑같아야
 * 한다. 다르면 글자를 건드린 것이고 그건 버그다.
 *
 * 발음 사전으로 바꾼 낱말은 당연히 다르므로 그 낱말은 빼고 본다.
 */
export function sameMeaning(original, speech) {
  const strip = (s) => {
    // ⚠️ 숫자는 양쪽 다 **읽는 꼴로 맞춰 놓고** 본다. 자막의 '5.26'과
    //    읽을 글의 '오 점 이 육'은 글자로는 다르지만 같은 말이다.
    //    안 맞춰 두면 숫자가 든 문장이 전부 "글자를 건드렸다"로 걸린다.
    let t = readNumbers(String(s ?? ''));
    for (const [from, to] of PRONOUNCE) {
      t = t.split(from).join('§').split(to).join('§');
    }
    if (SOFTEN_LIST_COMMAS) t = t.replace(/·/g, '');
    // 단위 붙여 읽기(이 회 말 → 이회말)도 공백만 다르니 같이 지운다.
    return t.replace(/[^가-힣0-9A-Za-z§]/g, '');
  };
  return strip(original) === strip(speech);
}
