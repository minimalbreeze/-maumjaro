// 숫자를 읽는 글로 바꾼다.
//
// ─────────────────────────────────────────────────────────────
// 왜 필요한가
// ─────────────────────────────────────────────────────────────
//
// 2026-11-07 운영자:
//
//   "5.26은 숫자로 적어야지. 읽을 때는 한글로 읽지만."
//   "42억 이런 것도 숫자로 자막을 만들어야지."
//
// 맞는 말이다. 그동안 대본에 "오 점 이 육", "사십이억"이라고 한글로
// 적었다. 그러면 **자막에도 그대로 나간다.** 눈으로 읽는 사람에게
// "오 점 이 육"은 읽기 어렵다. 숫자는 숫자로 보여야 한다.
//
// KIA 와 같은 원칙이다(speech.mjs 의 PRONOUNCE). 다른 점은 숫자가
// **끝이 없다**는 것이다. 목록으로 적을 수가 없어서 규칙으로 바꾼다.
//
//   대본·자막:  5.26  ·  42억  ·  176개  ·  .273
//   읽는 글:    오 점 이 육  ·  사십이억  ·  백칠십육 개  ·  이 할 칠 푼 삼 리
//
// ─────────────────────────────────────────────────────────────
// 한국어 숫자는 두 벌이다
// ─────────────────────────────────────────────────────────────
//
// 한자어(일·이·삼)와 고유어(하나·둘·셋)가 있고, 뒤에 오는 단위가
// 어느 쪽을 쓸지 정한다.
//
//   한자어   억 만 원 년 월 일 위 점 승 패 이닝 경기 번 회 루 퍼센트
//   고유어   명 개 살 마리 가지 곳
//
// ⚠️ 고유어 단위도 **스물을 넘으면 한자어로 읽는다.** "백칠십육 개"지
//    "백일흔여섯 개"가 아니다. 그래서 20 이하만 고유어로 간다.
//
// ⚠️ '번'은 두 뜻이 있다. "2번 타자"는 한자어(이 번)고 "두 번"은
//    고유어다. 야구 글에서 숫자 뒤의 '번'은 거의 타순이라 **한자어로
//    둔다.** 횟수를 말할 때는 대본에 "두 번"이라고 한글로 적는다.

/** 한자어 한 자리. */
const SINO_DIGIT = ['영', '일', '이', '삼', '사', '오', '육', '칠', '팔', '구'];

/** 자리값. */
const SINO_PLACE = ['', '십', '백', '천'];

/** 네 자리씩 끊어 붙이는 단위. */
const SINO_GROUP = ['', '만', '억', '조'];

/**
 * 고유어 수. 단위 앞에 올 때의 꼴이다 — "하나"가 아니라 "한 개".
 *
 * 0은 없다. 고유어에 영이 없어서 "영 개"는 한자어로 간다.
 */
const NATIVE = [
  null, '한', '두', '세', '네', '다섯', '여섯', '일곱', '여덟', '아홉', '열',
  '열한', '열두', '열세', '열네', '열다섯', '열여섯', '열일곱', '열여덟', '열아홉', '스무',
];

/**
 * 한자어 수의 **끝 글자**들. 숫자를 바꾼 뒤 그 뒤를 띄우는 데 쓴다.
 *
 * 영·일·이·삼·사·오·육·칠·팔·구 와 자리값 십·백·천·만·억·조다.
 * "백팔십삼" 다음에 "이닝"이 오면 그 사이를 띄운다.
 */
const SINO_TAIL = '[영일이삼사오육칠팔구십백천만억조]';

/** 고유어로 읽는 단위. 20 이하일 때만 쓴다. */
const NATIVE_UNITS = ['명', '개', '살', '마리', '가지', '곳', '군데', '사람', '경기', '번'];

/**
 * 고유어 단위이지만 **뒤에 무엇이 오느냐에 따라** 한자어로 가는 것.
 *
 * '번' 하나다. 야구에서 '번' 은 두 가지로 쓰인다.
 *
 *   횟수   "3번뿐이에요"   → **세 번**뿐이에요     (고유어)
 *   순번   "1번 타자"      → **일번** 타자          (한자어)
 *          "38번째"        → **삼십팔 번째**        (한자어)
 *          "35번"(등번호)  → **삼십오 번**          (한자어)
 *
 * 둘을 가르는 것은 바로 뒤에 오는 글자다. 순번일 때는 '째' 가 붙거나
 * 타순·지명 같은 말이 따라온다.
 *
 * ⚠️ 2026-11-08. '번' 을 조건 없이 고유어로 넣었다가 되돌렸다 —
 *    "1번 타자"가 "한 번 타자"가 된다. 야구 대본에서 자주 나오는 말이라
 *    그대로 두면 매 편에서 틀린다.
 */
const NATIVE_UNIT_EXCEPTIONS = {
  // ⚠️ 여기에 '째' 가 들어 있었다. 그래서 "7번째" 가 **"칠번째"** 로
  //    읽혔다 (2026-11-10 운영자: "칠번째 반지가 아니라 일곱번째 반지다").
  //
  //    번째는 **언제나 고유어**다 — 두 번째, 세 번째, 일곱 번째.
  //    타순의 '번' 만 한자어다 — 4번 타자는 "사번 타자"다.
  //    그 둘을 한 줄에 묶어 두는 바람에 반대로 걸렸다.
  번: /^\s*(타자|타순|타|지명|선발|홈런|투수)/,
};

/**
 * 「1번째」만은 "한 번째" 가 아니라 **"첫 번째"** 다.
 *
 * 고유어 수사 표에서 1은 '한' 인데, 차례를 셀 때만 '첫' 으로 바뀐다.
 * 2 이상은 표 그대로다 — 두 번째, 세 번째.
 */
const FIRST_ORDINAL = '첫';

/**
 * 한자어 수 **뒤를 띄우는** 단위 (2026-11-10).
 *
 * 기본은 붙이는 것이다. 여기 적힌 것만 띄운다.
 *
 * ⚠️ '월'·'일' 이 여기 있는 까닭 — 날짜가 이어지면 "십일월일일" 이
 *    되어 '매일' 처럼 들린다. 원래 주석이 경고하던 바로 그 자리다.
 *    그래서 날짜만 띄우고 나머지는 붙인다.
 */
const SPLIT_AFTER = new Set(['월', '일']);

/**
 * 달 이름에만 있는 예외 둘.
 *
 * 6월은 "육월"이 아니라 **유월**, 10월은 "십월"이 아니라 **시월**이다.
 * 다른 달은 규칙대로 읽는다. 이것만 어긋난다.
 */
const MONTH_EXCEPTION = { 6: '유', 10: '시' };

/**
 * 네 자리 이하를 한자어로 읽는다.
 *
 * 앞자리의 '일'은 떼어 읽는다 — 143은 "백사십삼"이지 "일백사십삼"이
 * 아니다. 다만 **맨 앞자리에서만** 뗀다. 2015의 '십'은 "이천십오"로
 * 그대로다.
 */
function sinoUnder10000(n) {
  if (n === 0) return '';
  let out = '';
  const digits = String(n).split('').map(Number);
  const len = digits.length;
  for (let i = 0; i < len; i += 1) {
    const d = digits[i];
    if (d === 0) continue;
    const place = SINO_PLACE[len - 1 - i];
    // 십·백·천 앞의 1은 안 읽는다. 일의 자리는 읽는다.
    if (d === 1 && place) out += place;
    else out += SINO_DIGIT[d] + place;
  }
  return out;
}

/**
 * 정수를 한자어로 읽는다.
 *
 *   143   → 백사십삼
 *   9723  → 구천칠백이십삼
 *   2026  → 이천이십육
 *   100000000 → 일억
 */
export function sinoNumber(n) {
  const num = Math.trunc(Math.abs(Number(n)));
  if (!Number.isFinite(num)) return '';
  if (num === 0) return '영';
  const groups = [];
  let rest = num;
  while (rest > 0) {
    groups.push(rest % 10000);
    rest = Math.floor(rest / 10000);
  }
  let out = '';
  for (let i = groups.length - 1; i >= 0; i -= 1) {
    if (groups[i] === 0) continue;
    // ⚠️ 만·억 앞의 1은 **읽는다.** "일억"이지 "억"이 아니다.
    //    십·백·천과 다르다.
    const head = groups[i] === 1 && i > 0 ? '일' : sinoUnder10000(groups[i]);
    out += head + SINO_GROUP[i];
  }
  return out;
}

/**
 * 타율·승률처럼 점으로 시작하는 세 자리를 할·푼·리로 읽는다.
 *
 *   .273 → 이 할 칠 푼 삼 리
 *   .407 → 사 할 영 푼 칠 리
 *   .400 → 사 할
 *   .000 → 영 할
 *
 * 뒤에서부터 0이면 떼고 읽는다. "사 할 영 푼 영 리"라고는 안 한다.
 */
export function rateNumber(digits) {
  const d = String(digits).padEnd(3, '0').slice(0, 3).split('').map(Number);
  const parts = [`${SINO_DIGIT[d[0]]} 할`];
  if (d[1] !== 0 || d[2] !== 0) parts.push(`${SINO_DIGIT[d[1]]} 푼`);
  if (d[2] !== 0) parts.push(`${SINO_DIGIT[d[2]]} 리`);
  return parts.join(' ');
}

/**
 * 소수점 아래는 **한 자씩** 읽는다.
 *
 *   5.26  → 오 점 이 육
 *   3.88  → 삼 점 팔 팔
 *   219.1 → 이백십구 점 일
 *
 * "오 점 이십육"이라고는 안 읽는다. 평균자책점도 승률도 그렇다.
 */
function decimalTail(digits) {
  return String(digits)
    .split('')
    .map((c) => SINO_DIGIT[Number(c)])
    .join(' ');
}

/**
 * 글 안의 숫자를 읽는 글로 바꾼다.
 *
 * 자막에는 숫자가 그대로 남는다 — 이 함수는 **읽을 글에만** 쓴다.
 */
export function readNumbers(text) {
  let out = String(text ?? '');

  // ⓪ 달 이름 예외를 먼저 뗀다. 뒤의 규칙이 "십월"로 만들기 전에.
  out = out.replace(/(^|[^\d])(\d{1,2})월/g, (m, pre, mm) => {
    const n = Number(mm);
    return MONTH_EXCEPTION[n] ? `${pre}${MONTH_EXCEPTION[n]}월` : m;
  });

  // 퍼센트 기호는 글자로 바꾼다. 그냥 두면 음성이 안 읽고 지나간다.
  out = out.replace(/%/g, ' 퍼센트');

  // ① 더하기. "4+2년" → "사 플러스 이 년" (2026-11-07 운영자).
  //
  //    계약을 "4+2년"이라고 적는 것은 야구 글의 관행이다 — 4년을
  //    보장하고 2년을 더 붙일 수 있다는 뜻이다. 눈에는 그 꼴이
  //    익었으니 자막에는 그대로 두고, 읽을 때만 풀어 준다.
  //
  //    ⚠️ 숫자 규칙보다 **먼저** 본다. 뒤로 미루면 4 와 2 가 따로
  //       바뀌고 '+' 만 남아서 음성이 그냥 지나간다.
  out = out.replace(/(\d+)\s*\+\s*(\d+)/g, (_m, a, b) => `${sinoNumber(a)} 플러스 ${sinoNumber(b)}`);

  // ② 분수. "3분의 1" → "삼분의 일". 다른 규칙보다 먼저 본다 —
  //    안 그러면 "3분"이 시간으로 읽힌다.
  //    ⚠️ 뒤에 한글이 붙으면 띄운다. 안 띄우면 "3분의 1이닝" 이
  //       "삼분의 일이닝" 이 되고, 음성이 '일이닝' 을 한 덩어리로
  //       읽는다. ⑤ 정수가 하는 것과 같은 일을 여기서도 한다.
  out = out.replace(/(\d+)분의\s*(\d+)/g, (m, a, b, offset, whole) => {
    const next = whole[offset + m.length] || '';
    const space = /[가-힣]/.test(next) ? ' ' : '';
    return `${sinoNumber(a)}분의 ${sinoNumber(b)}${space}`;
  });

  // ②-2 점수. "8-0" → "팔 대 영".
  //
  // 2026-11-08. 11화 대본을 읽혀 보고 찾았다. 전에는 하이픈을 그냥
  // 두어서 "팔-영" 이 됐고, 음성이 그 자리를 그냥 지나가 "팔영" 처럼
  // 들렸다. 야구 영상은 점수가 계속 나오니 매 편에서 어색해진다.
  //
  // ⚠️ ⑤ 정수보다 **먼저** 본다. 뒤로 미루면 8 과 0 이 따로 바뀌고
  //    하이픈만 남는다 — 4+2년 에서 겪은 그대로다.
  // ⚠️ 숫자-숫자 꼴만 본다. "1차전-3차전" 같은 범위는 대본에서
  //    "1차전부터 3차전까지"로 쓴다. 읽어서 뜻이 갈리는 자리는 글로
  //    분명히 적는 쪽이 맞다.
  out = out.replace(
    /(\d+)\s*-\s*(\d+)/g,
    (_m, a, b) => `${sinoNumber(a)} 대 ${sinoNumber(b)}`
  );

  // ③ 타율·승률. 점으로 시작하는 세 자리다.
  //    ⚠️ 앞에 숫자가 붙어 있으면 소수점이지 타율이 아니다 — 5.26 을
  //       여기서 잡으면 안 된다. 그래서 앞을 본다.
  out = out.replace(/(^|[^\d.])\.(\d{3})(?!\d)/g, (_m, pre, d) => `${pre}${rateNumber(d)}`);

  // ④ 소수. 1,234.56 처럼 자릿점이 든 것도 받는다.
  out = out.replace(/(\d[\d,]*)\.(\d+)/g, (_m, whole, frac) => {
    const w = sinoNumber(whole.replace(/,/g, ''));
    return `${w} 점 ${decimalTail(frac)}`;
  });

  // ⑤ 정수. 뒤에 붙은 단위를 보고 고유어로 갈지 정한다.
  const nativeUnit = NATIVE_UNITS.join('|');
  // ⚠️ 2026-11-08. 여기 숫자 꼴이 `\d[\d,]*` 였다. 그러면 **문장의
  //    쉼표를 숫자로 먹는다.** 11화 대본에서 찾았다.
  //
  //      "3차전 5-1, 4차전 10-5"
  //        → `[\d,]*` 가 "1," 까지 삼키고 쉼표가 사라진다
  //        → "삼차전 오 대 일사차전 십 대 오"
  //
  //    두 경기가 한 덩어리로 붙어 무슨 말인지 알 수 없게 된다.
  //    자릿점은 **세 자리 묶음일 때만** 받는다 — "9,723만" 은 받고
  //    "1," 는 안 받는다.
  out = out.replace(
    new RegExp(`(\\d+(?:,\\d{3})+|\\d+)\\s*(${nativeUnit})?`, 'g'),
    (m, num, unit, offset, whole) => {
      const n = Number(String(num).replace(/,/g, ''));
      if (!Number.isFinite(n)) return m;
      // 고유어 단위이면서 1~20 이면 고유어로 읽는다.
      // 단, 예외 꼴이 뒤따르면 한자어로 간다 ("1번 타자" → "일 번 타자").
      const after = whole.slice(offset + m.length);
      const blocked = unit && NATIVE_UNIT_EXCEPTIONS[unit]?.test(after);
      if (unit && !blocked && n >= 1 && n <= 20) {
        // 1번째 → "첫 번째". '한 번째' 라고 하지 않는다.
        if (n === 1 && unit === '번' && /^째/.test(after)) {
          return `${FIRST_ORDINAL} ${unit}`;
        }
        return `${NATIVE[n]} ${unit}`;
      }
      // ── 한자어 수는 뒤 단위에 **붙인다** (2026-11-10에 뒤집었다) ──
      //
      // 운영자: "7 전 4선승이 아니라 7전 4선승이다. **띄어읽기 오류가
      //          너무 많다.**"
      //
      // 원래는 반대였다 — 일단 띄우고, 붙여 읽을 것만 joinNumberUnits 의
      // 목록에 넣어 도로 붙였다. 그 구조로는 목록이 영영 안 찬다.
      // 하루에 여섯 번을 짚어 받았다(번째·오강권·십연승·그 경기를·
      // 유격수였고·칠 전). 고칠 때마다 목록에 한 줄씩 더하는 일이었다.
      //
      // 한국어에서 수와 단위는 붙여 읽는 쪽이 기본이다 — 구십승,
      // 이백팔안타, 칠전사선승제. 그래서 **기본을 붙이는 쪽으로** 바꾸고,
      // 띄어야 하는 자리만 아래 SPLIT_AFTER 에 적는다. 목록이 거꾸로
      // 짧아진다.
      //
      // ⚠️ 고유어 수사(열 개·다섯 경기)는 위에서 처리하고 **공백을
      //    그대로 둔다.** 그쪽은 띄어 읽는 게 맞다.
      if (unit) return SPLIT_AFTER.has(unit)
        ? `${sinoNumber(n)} ${unit}`
        : `${sinoNumber(n)}${unit}`;
      return sinoNumber(n);
    }
  );

  // ⑥ 바뀐 숫자와 뒤따르는 한글 사이를 띄운다.
  //
  // ⚠️ 처음에 **다 바꾼 뒤에 정규식으로** 띄우려 했다. 한자어 숫자
  //    글자 뒤에 한글이 오면 띄우는 식이었다. 그러면 이렇게 된다.
  //
  //      "네일은"    → "네일 은"      ('일'이 숫자 글자다)
  //      "삼십일 경기" → "삼 십 일 경기"  (글자마다 쪼개진다)
  //
  //    숫자를 다 바꾸고 나면 **어디까지가 숫자였는지 알 수가 없다.**
  //    한자어 숫자는 그냥 한글이라 이름과 구별이 안 된다.
  //
  //    그래서 **바꾸는 그 자리에서** 띄운다. 거기서는 숫자의 끝이
  //    어디인지 알고, 뒤에 무엇이 오는지도 볼 수 있다.
  //
  // 2026-11-07 운영자: "읽을 때 가끔 어색하게 띄어 읽기가 있는데
  // 그 부분만 좀 정리하면 좋겠다."
  //
  // 까닭은 공백이 들쭉날쭉했기 때문이다.
  //
  //   "5명"   → "다섯 명"      (고유어 단위라 공백이 붙었다)
  //   "183이닝" → "백팔십삼이닝"  (공백이 없다)
  //
  // 뒤엣것처럼 긴 덩어리가 통째로 이어지면 음성 모델이 어디서 끊을지를
  // 제 맘대로 정한다. "백팔십 삼이닝" 처럼 엉뚱하게 끊긴다.
  //
  // 그래서 **바꾼 숫자 뒤에는 늘 공백을 둔다.** 붙여 읽어야 하는 것
  // (이회말·삼차전 같은 것)은 뒤에서 joinNumberUnits 가 도로 붙인다 —
  // 그 둘이 서로 받쳐 주는 구조다.
  // ⑦ 겹친 공백을 하나로.
  return out.replace(/[ \t]{2,}/g, ' ');
}
